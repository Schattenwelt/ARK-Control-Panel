def translate(lang, key, **kw):
    if lang not in LANGS:
        lang = DEFAULT_LANG
    entry = TRANSLATIONS.get(key, {})
    text = entry.get(lang) or entry.get(DEFAULT_LANG) or key
    return text.format(**kw) if kw else text
